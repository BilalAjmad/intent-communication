import { randomBytes } from "node:crypto";
import type { Brief, InterviewAnswer, InterviewState } from "@intent/schema";
import type { StoragePort } from "../port-types.js";

const CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";

/** New `c_`-prefixed Crockford ULID, the shape BriefSchema requires. */
export function newBriefId(): string {
  const bytes = randomBytes(16);
  let out = "";
  for (let i = 0; i < 26; i++) out += CROCKFORD[(bytes[i % 16] as number) % 32];
  return `c_${out}`;
}

/**
 * Builds the approved brief from the interview state (final master order
 * 2026-11-21, section B: `/intent` ends by saving brief.json).
 *
 * The builder is deliberately honest: every field comes from a recorded answer
 * or the approved summary. It never invents colors, names or metrics. Fields
 * with no evidence stay empty.
 */
export interface BuildBriefOptions {
  /** ULID generated by the caller's CryptoPort. */
  id: string;
  /** ISO timestamp of the approval. */
  now: string;
}

function answerText(answer: unknown): string | null {
  if (typeof answer === "string") return answer.trim() || null;
  if (typeof answer === "number" || typeof answer === "boolean") return String(answer);
  if (Array.isArray(answer)) {
    const parts = answer.map(answerText).filter((v): v is string => Boolean(v));
    return parts.length > 0 ? parts.join(", ") : null;
  }
  if (answer && typeof answer === "object") {
    const record = answer as Record<string, unknown>;
    for (const key of ["text", "value", "choiceId", "label", "answer", "summaryChoice"]) {
      const value = record[key];
      if (typeof value === "string" && value.trim().length > 0) return value.trim();
    }
    if (Array.isArray(record["values"])) return answerText(record["values"]);
  }
  return null;
}

function byTopic(state: InterviewState, topic: string): string[] {
  const fromSummary = (state.lastSummary?.items ?? [])
    .filter((item) => item.topic === topic)
    .map((item) => item.text.trim())
    .filter((text) => text.length > 0);
  if (fromSummary.length > 0) return fromSummary;
  const out: string[] = [];
  for (const answer of state.answers) {
    if (answer.topic !== topic) continue;
    const text = answerText(answer.answer);
    if (text) out.push(text);
  }
  return out;
}

function firstAnswer(state: InterviewState): string | null {
  for (const answer of state.answers) {
    const text = answerText(answer.answer);
    if (text) return text;
  }
  return null;
}

function answerCount(state: InterviewState): number {
  return state.answers.filter((a: InterviewAnswer) => answerText(a.answer) !== null).length;
}

export function buildApprovedBrief(state: InterviewState, options: BuildBriefOptions): Brief {  const goals = byTopic(state, "goal");
  const users = byTopic(state, "users");
  const screens = byTopic(state, "screens");
  const flow = byTopic(state, "flow");
  const style = byTopic(state, "style");
  const content = byTopic(state, "content");
  const behavior = byTopic(state, "behavior");
  const edgeCases = byTopic(state, "edge-cases");

  const summaryText =
    state.lastSummary?.paragraph?.trim() ||
    `Approved after ${answerCount(state)} recorded answers.` +
      (state.lastSummary && state.lastSummary.items.length > 0
        ? ` Topics covered: ${[...new Set(state.lastSummary.items.map((item) => item.topic))].join(", ")}.`
        : "");

  return {
    id: options.id,
    version: 1,
    createdAt: options.now,
    updatedAt: options.now,
    title: firstAnswer(state)?.slice(0, 120) || state.lastSummary?.paragraph?.trim().slice(0, 120) || "Project Brief",
    summary: summaryText,
    goals,
    constraints: [...behavior, ...edgeCases],
    ...(users[0] ? { targetAudience: users[0] } : {}),
    successMetrics: goals.slice(0, 5),
    designDirection: {
      ...(style[0] ? { tone: style[0] } : {}),
      // No invented colors: the brief carries the user's style words, and the
      // /prototype art-direction step derives a contrast-checked palette.
      palette: [],
      ...(style[1] ? { typography: style[1] } : {}),
      inspiration: content.slice(0, 5),
    },
    technicalRequirements: [...screens, ...flow],
    outOfScope: [],
    approvalStatus: "approved",
    approvedAt: options.now,
    approvedBy: "user",
  };
}

/**
 * Persists the approved brief and links it to the interview state. Both the
 * MCP `ask_user` path and the Studio answer path call this on "Exactly right",
 * so brief.json exists no matter where the user approved the summary.
 */
export async function approveInterview(
  storage: Pick<StoragePort, "writeBrief" | "writeInterviewState">,
  state: InterviewState,
  now: string,
): Promise<Brief> {
  const brief = buildApprovedBrief(state, { id: newBriefId(), now });
  await storage.writeBrief(brief);
  state.briefId = brief.id;
  state.status = "complete";
  state.updatedAt = now;
  await storage.writeInterviewState(state);
  return brief;
}
