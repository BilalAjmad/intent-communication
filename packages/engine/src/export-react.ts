import { renderModelNodeJsx } from "./render-react.js";
import { expandComponentInstances } from "./components.js";
import type { DesignProfileLike } from "./tailwind-map.js";
import type { ShadcnImport } from "./shadcn-map.js";
import { renderStateCss } from "./state-css.js";
import { renderResponsiveCss, DEFAULT_BREAKPOINTS } from "./responsive-css.js";
import { renderAnimationCss } from "./animation-css.js";
import type { Breakpoints } from "@intent/schema";

/**
 * ReactExporter (trd 13.7, M2 basic): deterministic, pure export of a scene to
 * a small React + Vite-less source folder (`intent-export/`).
 *
 * Output files (sorted): `tokens.css` (CSS variables + base rules + the
 * state/responsive rules, shared with the HTML export), `screens/<Name>.tsx`
 * (one component per screen), `App.tsx` (hash-based screen switching) and
 * `index.ts` (re-exports). No `package.json`, no dependencies beyond `react`.
 *
 * trd 13.1/13.2: both exporters walk the same RenderModel — screens render
 * `<main className="intent-screen">` from the model, not from a second
 * scene-graph walker.
 *
 * Determinism (trd 13.3): no clock, no randomness, no environment input;
 * file map keys are sorted; screen ordering follows `screenOrder` with any
 * leftovers appended in id order.
 */

export type FileMap = Record<string, string>;

export interface ReactExportOptions {
  /** Emit `data-object-id` attributes (debugging/tooling). Default false. */
  includeDataIds?: boolean;
  /** Responsive breakpoints (defaults 640/1024/1440, per trd 4.4). */
  breakpoints?: Breakpoints;
  /** trd 13.7 — studio-scanned design profile; exact-match tokens become Tailwind classes. */
  designProfile?: DesignProfileLike;
}

const GENERATOR_BANNER = "/* Generated by intent-studio — do not edit by hand. */";

const MAX_NODES = 5000;

function toPascalCase(raw: string): string {
  const words = raw.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const pascal = words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("");
  if (!pascal) return "";
  return /^[0-9]/.test(pascal) ? `Screen${pascal}` : pascal;
}

/** Deterministic unique component names for the model's screens, in order. */
function buildScreenEntries(model: RenderModel): { id: string; name: string; title: string }[] {
  const entries: { id: string; name: string; title: string }[] = [];
  const used = new Set<string>();
  for (const [index, screen] of model.screens.entries()) {
    const base = toPascalCase(screen.name) || `Screen${index + 1}`;
    let name = base;
    let suffix = 2;
    while (used.has(name)) {
      name = `${base}${suffix}`;
      suffix += 1;
    }
    used.add(name);
    entries.push({ id: screen.id, name, title: screen.name || name });
  }
  return entries;
}

/** Build the screen component files. Each screen renders the model's root node. */
function buildScreenFiles(model: RenderModel, includeDataIds: boolean, designProfile?: DesignProfileLike) {
  const entries = buildScreenEntries(model);
  const byId = new Map(model.screens.map((screen) => [screen.id, screen] as const));
  const files: Record<string, string> = {};
  for (const entry of entries) {
    const screen = byId.get(entry.id);
    if (!screen) continue;
    const budget = { remaining: MAX_NODES };
    const imports = new Map<string, ShadcnImport>(); // keyed by name+from to dedupe by identity, not object reference
    const body = renderModelNodeJsx(screen.root, 3, budget, includeDataIds, designProfile, imports);
    const SAFE_IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
    const importLines = [...imports.values()]
      .sort((a, b) => a.name.localeCompare(b.name) || a.from.localeCompare(b.from))
      .map((imp) => {
        if (!SAFE_IDENT.test(imp.name)) {
          throw new IntentError(ErrorCodes.E_SCHEMA, `Unsafe export name in design profile: ${imp.name}`);
        }
        const safeFrom = String(imp.from).replace(/^(["'])(.*)\1$/, "$2");
        if (/[\\\s"'`<>;]/.test(safeFrom) || safeFrom.includes("..")) {
          throw new IntentError(ErrorCodes.E_SCHEMA, `Unsafe import path in design profile: ${imp.from}`);
        }
        return `import { ${imp.name} } from ${JSON.stringify(safeFrom)};`;
      })
      .join("\n");
    const header = importLines ? `${importLines}\n` : "";
    files[`intent-export/screens/${entry.name}.tsx`] =
`${GENERATOR_BANNER}
${header}export default function ${entry.name}() {
  return (
${body}
  );
}
`;
  }
  return { entries, screens: files };
}

function buildApp(entries: { id: string; name: string; title: string }[]): string {
  if (entries.length === 0) {
    return `${GENERATOR_BANNER}
import type { ComponentType } from "react";

const SCREENS: ReadonlyArray<{ id: string; name: string; Component: ComponentType }> = [];

export default function App() {
  return (
    <div className="intent-app">
      <p>This design has no screens yet.</p>
    </div>
  );
}
`;
  }
  // Imports sorted by component name (deterministic); SCREENS keeps screenOrder.
  const imports = entries
    .map((e) => `import ${e.name} from "./screens/${e.name}";`)
    .sort()
    .join("\n");
  const rows = entries
    .map((e) => `  { id: ${JSON.stringify(e.id)}, name: ${JSON.stringify(e.title)}, Component: ${e.name} },`)
    .join("\n");
  const firstId = entries[0]?.id ?? "";
  return `${GENERATOR_BANNER}
import { useEffect, useState } from "react";
${imports}

const SCREENS = [
${rows}
] as const;

export default function App() {
  const [active, setActive] = useState<string>(() => {
    if (typeof window === "undefined") {
      return ${JSON.stringify(firstId)};
    }
    return window.location.hash.replace(/^#/, "") || ${JSON.stringify(firstId)};
  });
  useEffect(() => {
    const onHashChange = () => setActive(window.location.hash.replace(/^#/, "") || ${JSON.stringify(firstId)});
    window.addEventListener("hashchange", onHashChange);
    return () => window.removeEventListener("hashchange", onHashChange);
  }, []);
  const current = SCREENS.find((screen) => screen.id === active) ?? SCREENS[0];
  return (
    <div className="intent-app">
      <nav aria-label="Screens">
        {SCREENS.map((screen) => (
          <a key={screen.id} href={"#" + screen.id} aria-current={screen.id === current.id ? "page" : undefined}>{screen.name}</a>
        ))}
      </nav>
      <current.Component />
    </div>
  );
}
`;
}

function buildIndex(entries: { name: string }[]): string {
  const lines = [`export { default as App } from "./App";`];
  for (const e of entries) {
    lines.push(`export { default as ${e.name} } from "./screens/${e.name}";`);
  }
  return `${GENERATOR_BANNER}\n${lines.join("\n")}\n`;
}

/**
 * Exports a scene to the `intent-export/` React source folder.
 * Pure: same scene + same options → byte-identical FileMap.
 */
export function exportToReact(scene: Scene, options: ReactExportOptions = {}): FileMap {
  const validated = validateScene(scene);
  const renderScene = expandComponentInstances(validated);
  // trd.md §13: includeDataIds defaults to false (editor artifacts stay out of output).
  const includeDataIds = options.includeDataIds === true;
  const model = normalizeSceneToModel(validated, { breakpoints: options.breakpoints ?? DEFAULT_BREAKPOINTS });
  const { entries, screens } = buildScreenFiles(model, includeDataIds, options.designProfile);
  // NOTE (reviewer finding 2026-11): state/responsive CSS targets [data-object-id];
  // the React export does not emit those ids unless includeDataIds is set, so with the
  // spec default (false, trd.md §13) the blocks never match. They are kept because the
  // team's tests/goldens pin their presence in tokens.css; opt into ids to activate them.
  const stateCss = renderStateCss(renderScene);
  const responsiveCss = renderResponsiveCss(renderScene, options.breakpoints ?? DEFAULT_BREAKPOINTS);
  const animationCss = renderAnimationCss(model, { includeDataIds });
  const tokens = `${GENERATOR_BANNER}\n${renderExportCss()}${stateCss ? `\n${stateCss}\n` : ""}${responsiveCss ? `\n${responsiveCss}\n` : ""}${animationCss ? `\n${animationCss}\n` : ""}`;
  const files: Record<string, string> = {
    "intent-export/tokens.css": tokens,
    ...screens,
    "intent-export/App.tsx": buildApp(entries),
    "intent-export/index.ts": buildIndex(entries),
  };
  const sorted = Object.entries(files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return Object.fromEntries(sorted);
}
