/**
 * ReactExporter (trd 13.7, M2 basic): deterministic, pure export of a scene to
 * a small React + Vite-less source folder (`intent-export/`).
 *
 * Output files (sorted): `tokens.css` (CSS variables + base rules shared with
 * the HTML export), `screens/<Name>.tsx` (one component per screen, named
 * after the screen title with a uniqueness pass), `App.tsx` (hash-based
 * screen switching) and `index.ts` (re-exports). No `package.json`, no
 * dependencies beyond `react`.
 *
 * Deviation from trd 13.1/13.2, documented honestly: there is no RenderModel
 * layer yet (the M1 HTML export renders directly from the scene). This
 * exporter therefore shares the *same* scene, validators, token CSS and
 * style-string builder as the HTML export instead of a RenderModel. When the
 * 13.2 RenderModel lands, both exporters should be re-pointed at it.
 *
 * Determinism (trd 13.3): no clock, no randomness, no environment input;
 * file map keys are sorted; screen ordering follows `screenOrder` with any
 * leftovers appended in id order.
 */

export type FileMap = Record<string, string>;

export interface ReactExportOptions {
  /** Emit `data-object-id` attributes (debugging/tooling). Default false. */
  includeDataIds?: boolean;
  /** Responsive breakpoints (defaults 640/1024/1440, per trd 4.4). */
  breakpoints?: Breakpoints;
}

const GENERATOR_BANNER = "/* Generated by intent-studio — do not edit by hand. */";

// Renders are bounded, same budgets as the HTML exporter.
const MAX_DEPTH = 200;
const MAX_NODES = 5000;

const ALLOWED_INPUT_TYPES = new Set(["text", "email", "password", "number", "tel", "url"]);

function toPascalCase(raw: string): string {
  const words = raw.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const pascal = words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("");
  if (!pascal) return "";
  return /^[0-9]/.test(pascal) ? `Screen${pascal}` : pascal;
}

/** kebab-case CSS declarations → JSX style object literal text (with braces). */
function styleObjectFor(
  style: Record<string, unknown>,
  extra?: ReadonlyArray<readonly [string, string]>,
): string | null {
  const entries: string[] = [];
  for (const [key, value] of styleDeclarations(style as Parameters<typeof styleDeclarations>[0])) {
    const camel = key.startsWith("--")
      ? key
      : key.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
    entries.push(`${JSON.stringify(camel)}: ${JSON.stringify(value)}`);
  }
  for (const [key, value] of extra ?? []) {
    entries.push(`${JSON.stringify(key)}: ${JSON.stringify(value)}`);
  }
  return entries.length ? `{ ${entries.join(", ")} }` : null;
}

function jsxText(value: unknown): string {
  const s = typeof value === "string" ? value : value == null ? "" : String(value);
  return `{${JSON.stringify(s)}}`;
}

const dataIdAttr = (obj: SceneObject, include: boolean): string =>
  include ? ` data-object-id={${JSON.stringify(obj.id)}}` : "";

function styleAttrFor(obj: SceneObject): string {
  const literal = styleObjectFor(obj.style);
  return literal ? ` style={${literal}}` : "";
}

function renderJsxObject(
  obj: SceneObject,
  allObjects: Record<string, SceneObject>,
  depth: number,
  budget: { remaining: number },
  includeDataIds: boolean,
): string {
  if (depth > MAX_DEPTH || budget.remaining <= 0) {
    throw new IntentError(ErrorCodes.E_LIMIT, "Scene exceeds render depth/size budget");
  }
  budget.remaining -= 1;
  const pad = "  ".repeat(depth);
  const children = obj.children
    .map((id) => {
      const child = allObjects[id];
      if (!child) {
        return `${pad}  {/* missing child ${String(id).replace(/[^A-Za-z0-9_-]/g, "?")} */}`;
      }
      return renderJsxObject(child, allObjects, depth + 1, budget, includeDataIds);
    })
    .join("\n");
  const style = styleAttrFor(obj);
  const dataId = dataIdAttr(obj, includeDataIds);

  switch (obj.type) {
    case "screen":
      // Screens are the roots; nested screens degrade to a div.
      return `${pad}<div className="intent-screen"${style}${dataId}>\n${children}\n${pad}</div>`;

    case "container":
      return `${pad}<div className="intent-container"${style}${dataId}>\n${children}\n${pad}</div>`;

    case "text":
      return `${pad}<p className="intent-text"${style}${dataId}>${jsxText(obj.props.content)}</p>`;

    case "button": {
      const variant = safeClassToken(obj.props.variant, "primary");
      const disabled = obj.props.disabled ? " disabled" : "";
      return `${pad}<button className="intent-button intent-button-${variant}" type="button"${disabled}${style}${dataId}>${jsxText(obj.props.label ?? "Button")}</button>`;
    }

    case "input": {
      const rawType = typeof obj.props.type === "string" ? obj.props.type : "text";
      const type = ALLOWED_INPUT_TYPES.has(rawType) ? rawType : "text";
      const placeholder = typeof obj.props.placeholder === "string" ? obj.props.placeholder : "";
      const value = typeof obj.props.value === "string" ? obj.props.value : "";
      const required = obj.props.required ? " required" : "";
      const disabled = obj.props.disabled ? " disabled" : "";
      return `${pad}<input className="intent-input" type={${JSON.stringify(type)}} placeholder={${JSON.stringify(placeholder)}} defaultValue={${JSON.stringify(value)}} aria-label={${JSON.stringify(placeholder || "Input")}}${required}${disabled}${style}${dataId} />`;
    }

    case "image": {
      const src = sanitizeUrl(obj.props.src);
      const alt = typeof obj.props.alt === "string" ? obj.props.alt : "";
      const fit = safeClassToken(obj.props.fit, "cover");
      return `${pad}<img className="intent-image intent-fit-${fit}" src={${JSON.stringify(src)}} alt={${JSON.stringify(alt)}}${style}${dataId} />`;
    }

    case "checkbox": {
      const label = typeof obj.props.label === "string" ? obj.props.label : "Checkbox";
      const checked = obj.props.checked ? " defaultChecked" : "";
      const disabled = obj.props.disabled ? " disabled" : "";
      const name = typeof obj.props.name === "string" && obj.props.name ? ` name={${JSON.stringify(obj.props.name)}}` : "";
      return `${pad}<label className="intent-checkbox"${style}${dataId}><input type="checkbox"${name}${checked}${disabled} /><span>{${JSON.stringify(label)}}</span></label>`;
    }

    case "radio": {
      const label = typeof obj.props.label === "string" ? obj.props.label : "Option";
      const checked = obj.props.checked ? " defaultChecked" : "";
      const disabled = obj.props.disabled ? " disabled" : "";
      const name = typeof obj.props.name === "string" && obj.props.name ? ` name={${JSON.stringify(obj.props.name)}}` : "";
      const value = typeof obj.props.value === "string" && obj.props.value ? ` value={${JSON.stringify(obj.props.value)}}` : "";
      return `${pad}<label className="intent-radio"${style}${dataId}><input type="radio"${name}${value}${checked}${disabled} /><span>{${JSON.stringify(label)}}</span></label>`;
    }

    case "switch": {
      const label = typeof obj.props.label === "string" ? obj.props.label : "Toggle";
      const checked = obj.props.checked ? " defaultChecked" : "";
      const disabled = obj.props.disabled ? " disabled" : "";
      const name = typeof obj.props.name === "string" && obj.props.name ? ` name={${JSON.stringify(obj.props.name)}}` : "";
      return `${pad}<label className="intent-switch"${style}${dataId}><input type="checkbox" role="switch"${name}${checked}${disabled} /><span className="switch-track"></span><span>{${JSON.stringify(label)}}</span></label>`;
    }

    case "link": {
      const label = typeof obj.props.label === "string" ? obj.props.label : "Link";
      const href = sanitizeUrl(obj.props.href);
      const target = safeClassToken(obj.props.target, "_self");
      const targetAttr = target === "_self" ? "" : ` target={${JSON.stringify(target)}}`;
      const SAFE_REL = new Set(["noopener", "noreferrer", "nofollow"]);
      const rawRel = typeof obj.props.rel === "string" ? obj.props.rel : "";
      const rels = rawRel.split(/\s+/).filter((t) => SAFE_REL.has(t));
      if (target === "_blank" && !rels.includes("noopener")) rels.push("noopener");
      const relAttr = rels.length ? ` rel={${JSON.stringify(rels.join(" "))}}` : "";
      const hrefAttr = href ? ` href={${JSON.stringify(href)}}` : "";
      return `${pad}<a className="intent-link"${hrefAttr}${targetAttr}${relAttr}${style}${dataId}>{${JSON.stringify(label)}}</a>`;
    }

    case "list": {
      const items = Array.isArray(obj.props.items) ? (obj.props.items as string[]) : [];
      const tag = obj.props.ordered === true ? "ol" : "ul";
      const lis = items.map((item) => `${pad}  <li>{${JSON.stringify(item)}}</li>`).join("\n");
      return `${pad}<${tag} className="intent-list"${style}${dataId}>\n${lis}\n${pad}</${tag}>`;
    }

    case "modal": {
      const title = typeof obj.props.title === "string" ? obj.props.title : "";
      const size = safeClassToken(obj.props.size, "md");
      const modalClass = size === "md" ? "intent-modal" : `intent-modal intent-modal-${size}`;
      const openAttr = obj.props.open ? " open" : "";
      const titleJsx = title ? `\n${pad}  <h2 className="intent-modal-title">{${JSON.stringify(title)}}</h2>` : "";
      return `${pad}<dialog className={${JSON.stringify(modalClass)}}${openAttr}${style}${dataId}>${titleJsx}\n${children}\n${pad}</dialog>`;
    }

    case "icon": {
      const styleLiteral = styleObjectFor(obj.style);
      return `${pad}${renderIconJsx(obj.props.icon, obj.props.size, obj.props.color, obj.props.label, { objectId: includeDataIds ? obj.id : undefined, styleObject: styleLiteral ?? undefined })}`;
    }

    case "divider": {
      const direction = obj.props.direction === "vertical" ? "vertical" : "horizontal";
      const thicknessRaw = typeof obj.props.thickness === "number" && Number.isFinite(obj.props.thickness) ? obj.props.thickness : 1;
      const thickness = Math.min(Math.max(Math.floor(thicknessRaw), 1), 32);
      const dimension: readonly [string, string] = direction === "horizontal" ? ["height", `${thickness}px`] : ["width", `${thickness}px`];
      // Prop thickness is appended last so it wins, matching the HTML export.
      const merged = styleObjectFor(obj.style, [dimension]);
      const styleLiteral = merged ?? `{ ${JSON.stringify(dimension[0])}: ${JSON.stringify(dimension[1])} }`;
      return `${pad}<hr className="intent-divider intent-divider-${direction}" role="separator" style={${styleLiteral}}${dataId} />`;
    }

    default:
      return `${pad}<div${style}${dataId}>\n${children}\n${pad}</div>`;
  }
}

/** Deterministic ordered list of screens (screenOrder first, then id-sorted leftovers). */
function orderedScreenIds(scene: Scene): string[] {
  const ordered = scene.screenOrder.filter((id) => scene.screens[id]);
  const rest = Object.keys(scene.screens).filter((id) => !ordered.includes(id)).sort();
  return [...ordered, ...rest];
}

/** Build the screen component name map and write the file contents. */
function buildScreenFiles(scene: Scene, includeDataIds: boolean) {
  const allObjects: Record<string, SceneObject> = { ...scene.objects };
  const entries: { id: string; name: string; title: string }[] = [];
  const used = new Set<string>();
  for (const [index, id] of orderedScreenIds(scene).entries()) {
    const screen = scene.screens[id];
    if (!screen) continue;
    const title = typeof screen.props.title === "string" ? screen.props.title : "";
    const base = toPascalCase(title) || `Screen${index + 1}`;
    let name = base;
    let suffix = 2;
    while (used.has(name)) {
      name = `${base}${suffix}`;
      suffix += 1;
    }
    used.add(name);
    entries.push({ id, name, title: title || name });
  }
  const files: Record<string, string> = {};
  for (const entry of entries) {
    const screen = scene.screens[entry.id];
    if (!screen) continue;
    // Render the screen's children (the <main> wrapper is part of the template).
    const budget = { remaining: MAX_NODES };
    const body = screen.children
      .map((id) => {
        const child = allObjects[id];
        if (!child) {
          return `      {/* missing child ${String(id).replace(/[^A-Za-z0-9_-]/g, "?")} */}`;
        }
        return renderJsxObject(child, allObjects, 3, budget, includeDataIds);
      })
      .join("\n");
    files[`intent-export/screens/${entry.name}.tsx`] =
`${GENERATOR_BANNER}
export default function ${entry.name}() {
  return (
    <main className="intent-screen" data-screen-id={${JSON.stringify(entry.id)}}>
${body}
    </main>
  );
}
`;
  }
  return { entries, screens: files };
}

function buildApp(entries: { id: string; name: string; title: string }[]): string {
  if (entries.length === 0) {
    return `${GENERATOR_BANNER}
import type { ComponentType } from "react";

const SCREENS: ReadonlyArray<{ id: string; name: string; Component: ComponentType }> = [];

export default function App() {
  return (
    <div className="intent-app">
      <p>This design has no screens yet.</p>
    </div>
  );
}
`;
  }
  // Imports sorted by component name (deterministic); SCREENS keeps screenOrder.
  const imports = entries
    .map((e) => `import ${e.name} from "./screens/${e.name}";`)
    .sort()
    .join("\n");
  const rows = entries
    .map((e) => `  { id: ${JSON.stringify(e.id)}, name: ${JSON.stringify(e.title)}, Component: ${e.name} },`)
    .join("\n");
  const firstId = entries[0]?.id ?? "";
  return `${GENERATOR_BANNER}
import { useEffect, useState } from "react";
${imports}

const SCREENS = [
${rows}
] as const;

export default function App() {
  const [active, setActive] = useState<string>(() => {
    if (typeof window === "undefined") {
      return ${JSON.stringify(firstId)};
    }
    return window.location.hash.replace(/^#/, "") || ${JSON.stringify(firstId)};
  });
  useEffect(() => {
    const onHashChange = () => setActive(window.location.hash.replace(/^#/, "") || ${JSON.stringify(firstId)});
    window.addEventListener("hashchange", onHashChange);
    return () => window.removeEventListener("hashchange", onHashChange);
  }, []);
  const current = SCREENS.find((screen) => screen.id === active) ?? SCREENS[0];
  return (
    <div className="intent-app">
      <nav aria-label="Screens">
        {SCREENS.map((screen) => (
          <a key={screen.id} href={\`#\${screen.id}\`} aria-current={screen.id === current.id ? "page" : undefined}>{screen.name}</a>
        ))}
      </nav>
      <current.Component />
    </div>
  );
}
`;
}

function buildIndex(entries: { name: string }[]): string {
  const lines = [`export { default as App } from "./App";`];
  for (const e of entries) {
    lines.push(`export { default as ${e.name} } from "./screens/${e.name}";`);
  }
  return `${GENERATOR_BANNER}\n${lines.join("\n")}\n`;
}

/**
 * Exports a scene to the `intent-export/` React source folder.
 * Pure: same scene + same options → byte-identical FileMap.
 */
export function exportToReact(scene: Scene, options: ReactExportOptions = {}): FileMap {
  const validated = validateScene(scene);
  const renderScene = expandComponentInstances(validated);
  const includeDataIds = options.includeDataIds === true;
  const { entries, screens } = buildScreenFiles(renderScene, includeDataIds);
  const stateCss = renderStateCss(renderScene);
  const responsiveCss = renderResponsiveCss(renderScene, options.breakpoints ?? DEFAULT_BREAKPOINTS);
  const tokens = `${GENERATOR_BANNER}\n${renderExportCss()}${stateCss ? `\n${stateCss}\n` : ""}${responsiveCss ? `\n${responsiveCss}\n` : ""}`;
  const files: Record<string, string> = {
    "intent-export/tokens.css": tokens,
    ...screens,
    "intent-export/App.tsx": buildApp(entries),
    "intent-export/index.ts": buildIndex(entries),
  };
  const sorted = Object.entries(files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return Object.fromEntries(sorted);
}
