function getInitPlan(projectRoot: string): { path: string; kind: "file" | "directory" }[] {
  const intentDir = resolve(projectRoot, ".intent");
  return [
    { path: resolve(intentDir, "scenes"), kind: "directory" },
    { path: resolve(intentDir, "locks"), kind: "directory" },
    { path: resolve(intentDir, "briefs"), kind: "directory" },
    { path: resolve(intentDir, "feedback"), kind: "directory" },
    { path: resolve(intentDir, "interview"), kind: "directory" },
    { path: resolve(intentDir, "config.json"), kind: "file" },
    { path: resolve(intentDir, ".gitignore"), kind: "file" },
    { path: resolve(intentDir, "scenes", "default.json"), kind: "file" },
    { path: resolve(intentDir, "rules"), kind: "directory" },
  ];
}

async function initCommand(projectRoot: string, options?: { dryRun?: boolean }): Promise<void> {
  const dryRun = options?.dryRun === true;
  const plan = getInitPlan(projectRoot);

  if (dryRun) {
    console.log(chalk.bold("DRY RUN — no files will be written"));
    console.log(chalk.gray("  Project root: " + projectRoot));
    console.log("  Would create:");
    for (const item of plan) {
      console.log(`  ${item.kind === "directory" ? "+" : "·"} ${item.path}`);
    }
    // Agent MCP configs: report the merge, write nothing.
    const mergePlan = await mergeAgentMcpConfigs(projectRoot, { dryRun: true });
    console.log("  Would merge MCP server \"intent\" into (other servers kept):");
    for (const report of mergePlan) {
      console.log(`  ${report.changed ? "M" : "="} ${report.file}`);
    }
    const agentsReport = await ensureAgentsIntentBlock(projectRoot, { dryRun: true });
    console.log(`  Would write AGENTS.md intent block: ${agentsReport.action} (${agentsReport.file})`);
    return;
  }

  const spinner = ora("Initializing Intent project...").start();
  const intentDir = resolve(projectRoot, ".intent");
  const scenesDir = resolve(intentDir, "scenes");
  const locksDir = resolve(intentDir, "locks");
  const briefsDir = resolve(intentDir, "briefs");
  const feedbackDir = resolve(intentDir, "feedback");
  const interviewDir = resolve(intentDir, "interview");

  await fs.mkdir(scenesDir, { recursive: true });
  await fs.mkdir(locksDir, { recursive: true });
  await fs.mkdir(briefsDir, { recursive: true });
  await fs.mkdir(feedbackDir, { recursive: true });
  await fs.mkdir(interviewDir, { recursive: true });

  // Default config
  const configPath = resolve(intentDir, "config.json");
  const defaultConfig = {
    version: 1,
    projectName: "Intent Project",
    previewPort: 3456,
    studioPort: 3457,
    mcpPort: 3458,
    maxBytes: 32768,
    autoSave: true,
    lockTTL: 30000,
    breakpoints: { sm: 640, md: 1024, lg: 1440 },
  };
  await fs.writeFile(configPath, JSON.stringify(defaultConfig, null, 2));

  // .intent/.gitignore (trd 14.3): agent working state stays out of git;
  // scene/locks/versions/config stay IN git.
  const gitignorePath = resolve(intentDir, ".gitignore");
  const gitignore = [
    "# .intent/.gitignore — generated by `intent init` (trd 14.3)",
    "# Agent working state — do not commit:",
    "patches/",
    "annotations/",
    "interview/",
    "runtime.json",
    "state.json",
    "tmp/",
    "logs/",
    "metrics.json",
    "# Explicitly NOT ignored (trd 14.3): scene.json, locks.json, versions/, config.json, profile.json, design-profile.json",
    "",
  ].join("\n");
  await fs.writeFile(gitignorePath, gitignore, "utf-8");

  // Generate skill files
  await import("@intent/skills").then((m) => m.generateAllSkillFiles(projectRoot));

  // Create default scene
  const defaultScene = {
    version: 1,
    revision: 0,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    screens: {},
    objects: {},
    screenOrder: [],
    metadata: { name: "Untitled Project", tags: [] },
  };
  const scenePath = resolve(scenesDir, "default.json");
  await fs.writeFile(scenePath, JSON.stringify(defaultScene, null, 2));

  // Agent MCP configs: merge the "intent" server into .mcp.json + .cursor/mcp.json
  try {
    const mergeReports = await mergeAgentMcpConfigs(projectRoot, { dryRun: false });
    for (const report of mergeReports) {
      console.log(chalk.gray(`  MCP: ${report.changed ? "merged" : "unchanged"} ${report.file}`));
    }
  } catch (err) {
    spinner.fail(chalk.red("Intent project created, but the agent MCP configs could not be merged"));
    throw err;
  }

  // AGENTS.md intent pointer block (context.md 8.4): agents pick up the rules
  try {
    const agentsReport = await ensureAgentsIntentBlock(projectRoot, { dryRun: false });
    console.log(chalk.gray(`  AGENTS.md: ${agentsReport.action} intent block (${agentsReport.file})`));
  } catch (err) {
    spinner.fail(chalk.red("Intent project created, but AGENTS.md could not be updated"));
    throw err;
  }

  spinner.succeed(chalk.green("Intent project initialized"));
  console.log(chalk.gray(`  Project root: ${projectRoot}`));
  console.log(chalk.gray(`  Config: ${configPath}`));
  console.log(chalk.gray(`  Gitignore: ${gitignorePath}`));
  console.log(chalk.gray(`  Default scene: ${scenePath}`));
  console.log(chalk.gray(`  Skill rules: ${resolve(projectRoot, ".intent", "rules")}`));
  console.log(chalk.gray("  How to start: say \"Design a booking app for my salon\" to your agent."));
  console.log(chalk.gray("  Agent configs: .mcp.json (Claude Code) and .cursor/mcp.json (Cursor) — review them before approving."));
}

async function doctorCommand(projectRoot: string): Promise<void> {
  const spinner = ora("Running diagnostics...").start();
  const issues: string[] = [];
  const warnings: string[] = [];

  const intentDir = resolve(projectRoot, ".intent");
  const configPath = resolve(intentDir, "config.json");
  const scenesDir = resolve(intentDir, "scenes");
  const rulesDir = resolve(intentDir, "rules");

  // Check .intent directory
  try {
    await fs.access(intentDir);
  } catch {
    issues.push(".intent directory not found — run 'intent init'");
    spinner.fail(chalk.red("Diagnostics failed"));
    printResults(issues, warnings);
    return;
  }

  // Check config
  try {
    const configContent = await fs.readFile(configPath, "utf-8");
    const config = JSON.parse(configContent);
    if (config.version !== 1) {
      warnings.push(`Config version is ${config.version}, expected 1`);
    }
  } catch {
    issues.push("config.json missing or invalid");
  }

  // Check scenes
  try {
    const scenes = await fs.readdir(scenesDir);
    if (scenes.length === 0) {
      warnings.push("No scenes found");
    }
  } catch {
    issues.push("Scenes directory not accessible");
  }

  // Check skill rules
  try {
    const rules = await fs.readdir(rulesDir);
    const required = ["intent-core.md", "tool-usage.md", "design-principles.md", "studio.md"];
    for (const req of required) {
      if (!rules.includes(req)) {
        warnings.push(`Missing skill rule: ${req}`);
      }
    }
  } catch {
    warnings.push("Skill rules directory not found — run 'intent init' to regenerate");
  }

  // Check Node.js version
  const nodeVersion = process.version;
  const versionParts = nodeVersion.slice(1).split(".");
  const major = parseInt(versionParts[0] || "0", 10);
  if (major < 20) {
    warnings.push(`Node.js ${nodeVersion} — recommend >=20`);
  }

  spinner.succeed(chalk.green("Diagnostics complete"));
  printResults(issues, warnings);
}

function printResults(issues: string[], warnings: string[]): void {
  if (issues.length > 0) {
    console.log(chalk.red("\nIssues:"));
    for (const issue of issues) console.log(chalk.red(`  ✗ ${issue}`));
  }
  if (warnings.length > 0) {
    console.log(chalk.yellow("\nWarnings:"));
    for (const warn of warnings) console.log(chalk.yellow(`  ⚠ ${warn}`));
  }
  if (issues.length === 0 && warnings.length === 0) {
    console.log(chalk.green("\nAll checks passed!"));
  }
}

/** Reads .intent/config.json `breakpoints` if present and valid; defaults otherwise. */
async function readProjectBreakpoints(projectRoot: string): Promise<Breakpoints | undefined> {
  try {
    const raw = await fs.readFile(resolve(projectRoot, ".intent", "config.json"), "utf8");
    const config: unknown = JSON.parse(raw);
    const rawBreakpoints =
      config && typeof config === "object" && "breakpoints" in config ? (config as { breakpoints: unknown }).breakpoints : undefined;
    if (rawBreakpoints === undefined) return undefined;
    const parsed = BreakpointsSchema.safeParse(rawBreakpoints);
    return parsed.success ? parsed.data : undefined;
  } catch {
    return undefined; // unreadable or absent config — engine defaults apply
  }
}

async function printAcceptanceRate(projectRoot: string, sceneId: string, scene: { objects: Record<string, { type: string }> }): Promise<void> {
  // trd 17.2: the acceptance-rate metric is export *output metadata* — printed
  // to the console, never embedded in the exported artifact.
  try {
    const baseline = await findFirstRenderBaseline(projectRoot);
    if (!baseline) {
      console.log(chalk.dim("acceptance rate: not enough data yet — no first-render baseline in .intent/versions/"));
      return;
    }
    const nonScreen = (objects: Record<string, { type: string }>) => {
      const out: Record<string, { type: string }> = {};
      for (const [id, obj] of Object.entries(objects)) {
        if (obj.type === "screen") continue;
        out[id] = obj;
      }
      return out;
    };
    const storage = createFileStoragePort(projectRoot);
    const feedback = await storage.readFeedback(sceneId);
    const appliedPatches: AppliedPatchRef[] = feedback
      .filter((f) => f.status === "applied" && typeof f.appliedAt === "string" && (f.appliedAt as string) >= baseline.createdAt)
      .map((f) => ({ objectId: f.objectId as string | null, appliedAt: f.appliedAt }));
    const metrics = computeAcceptanceRate({
      baselineObjects: nonScreen(baseline.scene.objects as Record<string, { type: string }>),
      currentObjects: nonScreen(scene.objects),
      appliedPatches,
    });
    if (!metrics.available) {
      console.log(chalk.dim(`acceptance rate: not enough data — ${metrics.reason ?? "unavailable"}`));
      return;
    }
    const pct = ((metrics.acceptanceRate ?? 0) * 100).toFixed(1);
    console.log(
      chalk.dim(
        `acceptance rate: ${pct}% (${metrics.unchanged}/${metrics.baselineObjectsStillPresent} baseline objects unchanged; ${metrics.removedAfterBaseline} removed, ${metrics.addedAfterBaseline} added, baseline ${baseline.createdAt})`,
      ),
    );
  } catch {
    // Metric is best-effort output metadata — never block the export on it.
    console.log(chalk.dim("acceptance rate: unavailable (see .intent/versions and feedback files)"));
  }
}

async function exportCommand(projectRoot: string, options: { scene?: string; output?: string; format?: string }): Promise<void> {
  const spinner = ora("Exporting scene...").start();
  const sceneId = options.scene || "default";
  const format = (options.format || "html").toLowerCase();

  try {
    const storage = createFileStoragePort(projectRoot);
    const scene = await storage.readScene(sceneId);

    if (!scene) {
      spinner.fail(chalk.red(`Scene '${sceneId}' not found`));
      process.exitCode = 1;
      return;
    }

    const breakpoints = await readProjectBreakpoints(projectRoot);

    if (format === "html") {
      const outputPath = options.output || resolve(projectRoot, `export-${sceneId}.html`);
      await exportSceneToFile(scene, outputPath, {
        includeStyles: true,
        includeScripts: true,
        inlineAssets: true,
        breakpoints,
      });
      spinner.succeed(chalk.green(`Exported to ${outputPath}`));
      await printAcceptanceRate(projectRoot, sceneId, scene);
      return;
    }

    if (format === "react") {
      const outDir = options.output || resolve(projectRoot, `export-${sceneId}-react`);
      const files = exportToReact(scene, { breakpoints });
      let written = 0;
      for (const [relative, content] of Object.entries(files)) {
        // FileMap keys come from the generator; validate them anyway — this
        // command writes attacker-influenced output to disk.
        if (!/^intent-export\/[A-Za-z0-9._\-/]+$/.test(relative) || relative.includes("..")) {
          throw new Error(`Unsafe export path: ${relative}`);
        }
        const target = resolve(outDir, relative);
        const root = resolve(outDir);
        if (target !== root && !target.startsWith(root + sep)) {
          throw new Error(`Export path escapes output directory: ${relative}`);
        }
        await fs.mkdir(dirname(target), { recursive: true });
        await fs.writeFile(target, content, "utf8");
        written += 1;
      }
      spinner.succeed(chalk.green(`Exported ${written} files to ${outDir}`));
      await printAcceptanceRate(projectRoot, sceneId, scene);
      return;
    }

    spinner.fail(chalk.red(`Unsupported format: ${format} (supported: html, react)`));
    process.exitCode = 1;
  } catch (err) {
    spinner.fail(chalk.red("Export failed: " + (err instanceof Error ? err.message : String(err))));
    process.exitCode = 1;
  }
}

export function createCLI(): Command {
  const program = new Command();

  program
    .name("intent")
    .description("Intent — browser-first SPA monorepo for closing the intent gap")
    .version("0.1.0")
    .option("-p, --path <path>", "Project root path", process.cwd());

  program
    .command("init")
    .description("Initialize a new Intent project in the current directory")
    .option("--dry-run", "Print the files init would create; do not write anything")
    .action(async (options) => {
      await initCommand(resolve(program.opts()["path"] as string), {
        dryRun: options.dryRun === true,
      });
    });

  program
    .command("mcp")
    .description("Start the MCP server on stdio (intended to be launched by an agent)")
    .action(async () => {
      try {
        await runMcpStdio(resolve(program.opts()["path"] as string));
      } catch (err) {
        // stderr is fine for agents; stdout must stay pure protocol.
        console.error(chalk.red("intent mcp failed: " + (err instanceof Error ? err.message : String(err))));
        process.exitCode = 1;
      }
    });

  program
    .command("doctor")
    .description("Run diagnostics on the Intent project")
    .action(async () => {
      await doctorCommand(resolve(program.opts()["path"] as string));
    });

  program
    .command("export")
    .description("Export a scene to HTML or a React source folder")
    .option("-s, --scene <sceneId>", "Scene ID to export", "default")
    .option("-o, --output <path>", "Output path (file for html, directory for react)")
    .option("-f, --format <format>", "Export format (html|react)", "html")
    .action(async (options) => {
      await exportCommand(resolve(program.opts()["path"] as string), {
        scene: options.scene,
        output: options.output ? resolve(options.output) : undefined,
        format: options.format,
      });
    });

  return program;
}

export async function runCLI(args: string[] = process.argv): Promise<void> {
  const program = createCLI();
  await program.parseAsync(args);
}

